//        while 循环
//
// 【知识点说明】
// while 循环是“当型”循环：先判断条件表达式，条件为真（非 0）时执行循环体，
// 执行完后再回头判断条件，如此反复，直到条件为假（0）才退出循环。
//
// 语法规则：
//     while (条件表达式)
//     {
//         循环体;   // 条件为真时反复执行
//     }
//
// 注意事项：
// 1. 循环体执行前会先判断条件，因此若一开始条件就为假，循环体一次也不会执行。
// 2. 循环体内必须要有能使条件最终变为假的语句，否则会形成死循环。
// 3. 条件表达式返回的“真/假”与 if 语句中的规则一致（非 0 为真，0 为假）。
#include <iostream>
#include <string>

using namespace std;

int main()
{
    string a;
    // 当输入流中还有数据可读时，反复读取并处理；
    // cin >> a 会返回 cin 引用，流正常时条件为真，遇到文件末尾或出错时为假。
    while (cin >> a) {
        cout << a + "编程." << endl;   // 每读入一个词，就在其后拼接并输出
    }
    return 0;
}
