//                                                                  逻辑运算符           与 或 非

//
// 【知识点说明】
// 逻辑运算符用于连接多个条件，结果同样为布尔值（1 为真，0 为假）。
// 常见逻辑运算符：
//   && 逻辑与：两边都为真结果才为真（有假必假）。
//   || 逻辑或：两边只要有一个为真结果就为真（有真必真）。
//   !  逻辑非：取反，真变假、假变真。
// 运算规则：
//   1. 非 0 的值都视为“真”，0 视为“假”。
//   2. 结果只有 0 或 1。
// 注意事项：
//   - && 和 || 具有“短路”特性：&& 左边为假时不再计算右边；
//     || 左边为真时不再计算右边。
//   - 注意区分逻辑与 &&（双符号）和位与 &、逻辑或 || 和位或 |。

/*
 * 与 &&
 * 或 ||
 * 非 !
 */


#include <iostream>

using namespace std;

int main()
{
    // 与 有假必假
    cout << (0 && 0) << endl;   // 0 && 0 = 0
    cout << (0 && 1) << endl;   // 0 && 1 = 0
    cout << (1 && 0) << endl;   // 1 && 0 = 0
    cout << (1 && 1) << endl;   // 1 && 1 = 1

    cout << "----" << endl;     // 分隔线

    // 或 有真必真
    cout << (0 || 0) << endl;   // 0 || 0 = 0
    cout << (0 || 1) << endl;   // 0 || 1 = 1
    cout << (1 || 0) << endl;   // 1 || 0 = 1
    cout << (1 || 1) << endl;   // 1 || 1 = 1

    cout << "----" << endl;

    // 非 非真即假 非假即真
    cout << !0 << endl;         // !0 = 1
    cout << !2 << endl;         // 2 非 0 视为真，!2 = 0

    cout << "----" << endl;

    int a = !(5>4) && (7-8) && (0-1);   // !1=0，&& 短路后整体为 0
    cout << a << endl;

    int b = !(1 || 1 && 0);     // && 优先级高于 ||：1&&0=0，1||0=1，取反得 0
    cout << b << endl;

    return 0;
}
