//                               左移运算符

//
// 【知识点说明】
// 左移运算符 << 把整数的二进制位整体向左移动指定的位数。
// 运算规则：
//   1. 左移 n 位，等价于该数乘以 2 的 n 次方：x << n 相当于 x * 2^n。
//   2. 左边移出的位被丢弃，右边空出的位补 0。
// 注意事项：
//   - 移位位数必须是合法的非负整数，移动负数位是未定义行为（结果不可靠）。
//   - 左移可能发生溢出：当有效位被移出取值范围时，结果会不正确。
//   - 这里 << 是移位运算符；cout 输出时也用 <<，那是流插入运算符，含义不同。

#include <iostream>

// x << y  =      x * 2y

using namespace std;

int main()
{
    int x = 0b11;          // 二进制 11，即 3
    x = (x << 1);          // 左移 1 位变成 110，即 6
    cout << x << endl;     // 6

    cout << (x << 4) <<endl;   // 6 << 4 = 6 * 16 = 96

    // 负数的左移：补码整体左移，结果仍为负数
    int y = -1;
    y = (y << 1);
    cout << y << endl;     // -2

    // 左移负数位 ——不允许：这是未定义行为，结果不可靠
    int z = 64;
    z = (z << (-1));
    cout << z << endl;

    // 左移溢出：这里 64 << 10 = 65536 仍在 int 范围内，可作演示；
    // 真正溢出发生在左移位数过大或数值过大时。
    int a = 64;
    a = (a << 10);
    cout << a << endl;

    return 0;
}
