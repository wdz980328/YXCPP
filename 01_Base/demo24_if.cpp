//        if 语句
//
// 【知识点说明】
// if 语句是最基本的条件分支语句，根据“条件表达式”的真假来决定是否执行某段代码。
//
// 语法规则：
//     if (条件表达式)
//     {
//         语句块;   // 条件为真（非 0）时执行
//     }
//
// 注意事项：
// 1. 条件表达式的结果为“真（非 0）”时执行语句块，为“假（0）”时跳过。
// 2. 语句块只有一条语句时花括号 {} 可以省略，但建议始终保留，避免歧义。
// 3. 条件表达式必须写在圆括号 () 中，不能省略。
#include <iostream>

using namespace std;

int main()
{
    int a = 233;
    // 计算 a % 2（a 对 2 取余数），判断余数是否等于 1，即判断 a 是否为奇数
    if (a % 2 == 1) {
        cout << "a 是一个奇数" << endl;   // 条件成立时输出
    }

    return 0;
}
