//                                           右移运算符

//
// 【知识点说明】
// 右移运算符 >> 把整数的二进制位整体向右移动指定的位数。
// 运算规则：
//   1. 右移 n 位，等价于该数除以 2 的 n 次方（取整数部分）。
//   2. 对于非负数，左边空出的位补 0（逻辑右移）；
//      对于负数，左边补 1 还是 0 取决于编译器（通常补 1，即算术右移）。
//   3. 移出最低位的位被丢弃。
// 常见用途：去掉低位、取出某一位的值、快速除以 2 的幂等。
// 注意事项：
//   - 移位位数必须是合法的非负整数，移动负数位是未定义行为。
//   - 负数右移的结果与实现相关，编写可移植代码时应谨慎。
//   - 这里 >> 是移位运算符；cin 输入时也用 >>，那是流提取运算符，含义不同。

#include <iostream>

using namespace std;


int main()
{
    int a = 0b111;         // 二进制 111，即 7
    a = (a >> 1);          // 右移 1 位变成 11，即 3
    cout << a << endl;     // 3

    //负数的右移：-1 右移 1 位，通常仍为 -1（算术右移补 1）
    int b = -1;
    cout << (-1 >> 1) << endl;   // -1

    // 去掉低 k 位：右移 7 位后，只剩最高位
    int c = 0b10000101;
    cout << (c >> 7) << endl;    // 0b1，即 1

    // 取到第 低k 位的值：先右移 4 位，再与 1 相与
    int d = 0b101010101;
    cout << ((d >> 4) & 1) << endl;  // 取出第 4 位（从 0 开始数）

    return 0;
}
