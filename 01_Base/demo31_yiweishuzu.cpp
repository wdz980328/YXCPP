//                                              一维数组
//
// 【知识点说明】
// 一维数组是一组相同类型数据的集合，在内存中连续存放，通过下标来访问其中的元素。
//
// 语法规则：
//     类型 数组名[元素个数];
//     例如：int a[10];        // 定义可存放 10 个 int 的数组
//
// 注意事项：
// 1. 下标从 0 开始，最后一个元素的下标是“元素个数 - 1”，访问时不能越界。
// 2. 定义时可用 {} 初始化，如 int a[1024] = {0}; 表示全部元素初始化为 0。
// 3. 数组名代表数组首元素的内存地址，单独使用数组名时通常表示该地址。
#include <iostream>

using namespace std;

int main()
{
    int a[1024]={0};      // 定义含 1024 个 int 的数组，并全部初始化为 0
    double b[520];        // 定义含 520 个 double 的数组（未初始化，值不确定）
    char c[1314];         // 定义含 1314 个 char 的数组

    int x1[10], x2[20];   // 可在一行定义多个数组

    // 数组元素的访问
    a[0] = 343;               // 给下标为 0 的元素（第一个元素）赋值
    cout << a[0] << endl;     // 输出下标为 0 的元素

    // 用 for 循环遍历数组：i 从 0 到 1023，依次访问每个元素
    for (int i = 0; i<1024; ++i) {
        cout << a[i] << endl;
    }

    return 0;
}
