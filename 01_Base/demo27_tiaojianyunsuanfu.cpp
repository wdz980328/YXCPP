//                                       条件运算符
//
// 【知识点说明】
// 条件运算符（?:）是 C++ 中唯一的三元运算符，可以根据一个条件的真假，
// 从两个表达式中选出一个作为整个表达式的结果。
//
// 语法规则：
//     表达式1 ? 表达式2 : 表达式3;
//     —— 先计算表达式1，若为真（非 0）则结果是表达式2 的值，否则是表达式3 的值。
//
// 注意事项：
// 1. 条件运算符会先求值、后返回结果，因此常用来替代简单的 if else 赋值。
// 2. 表达式2 和表达式3 的类型应尽量一致，否则会按规则发生隐式类型转换。
// 3. 条件运算符可以嵌套使用（如 a>b ? (a>c?a:c) : b），但嵌套过深会降低可读性。
#include <iostream>

using namespace std;

int main()
{
    int a = 3, b = 4, c = 5;
    int x = -1;
    // 用 if else 求 a、b 中较大者，赋给 x
    if (a > b) {
        x = a;
    }
    else {
        x = b;
    }

    // 表达式1 ? 表达式2 : 表达式3；
    // 上面 if else 的等价写法：a > b 为真则取 a，否则取 b
    x = (a > b ? a : b);
    // 条件运算符的嵌套：先判断 a>b，成立则再在 a、c 中取较大者，否则取 b
    x = (a>b) ? ((a>c) ? a:c):b;
    return 0;
}
