//                                              位与运算符

//
// 【知识点说明】
// 位与运算符 & 是“按位与”，对两个整数二进制表示的每一位进行与运算。
// 运算规则（对单个二进制位）：
//   1 & 1 = 1，其余（0 & 0、0 & 1、1 & 0）都为 0，即“有 0 必 0”。
// 常见用途：
//   - 判断奇偶：x & 1，结果为 1 是奇数，为 0 是偶数。
//   - 保留/提取某些位：与对应位为 1 的掩码相与。
//   - 将某些位清零：与对应位为 0 的掩码相与。
//   - 判断 2 的幂：x 是 2 的幂时，x & (x - 1) 等于 0。
// 注意事项：
//   - & 是位运算符，&& 是逻辑与，二者作用不同。
//   - 位运算按二进制位一一对应，需注意补码表示。

#include <iostream>

using namespace std;

int main()
{
    // 二元运算符 & 有0必0
    int a = 0b1010;                 // 二进制 1010
    int b = 0b0110;                 // 二进制 0110
    cout << (a & b) << endl;        // 1010 & 0110 = 0010，即 2

    // 奇偶性：x & 1 等价于 x % 2
    cout << 5 % 2 << endl;          // 5 % 2 = 1（奇数）
    cout << (5 & 1) << endl;        // 101 & 001 = 1，说明 5 是奇数

    // 获取一个数二进制的后五位：与掩码 0b11111 相与
    int c = 0b1010010101001;
    cout << (c & 0b11111) << endl;

    // 将末5位归零
    int d = 0b1111111111111111;
    cout << (c & d) << endl;        // d 为全 1 掩码，与全 1 相与结果不变（演示掩码思想）

    // 消除末尾连续的1
    int e = 0b101010111111;
    cout << (e & (e + 2)) << endl;

    // 2的幂判定：2 的幂满足 (f & (f-1)) == 0
    int f = 0b100000000;
    (f > 0) && ((f & (f - 1)) == 0);

    return 0;
}
