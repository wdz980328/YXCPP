//                                              异或运算符

//
// 【知识点说明】
// 异或运算符 ^ 是“按位异或”，对两个整数二进制表示的每一位进行异或运算。
// 运算规则（对单个二进制位）：
//   相同为 0，不同为 1：0 ^ 0 = 0，1 ^ 1 = 0，0 ^ 1 = 1，1 ^ 0 = 1。
// 可理解为“不带进位的二进制加法”。
// 重要性质：
//   1. 任何数与 0 异或，结果还是它本身：x ^ 0 = x。
//   2. 任何数与自身异或，结果为 0：x ^ x = 0。
//   3. 异或满足交换律和结合律。
// 常见用途：交换两个变量、翻转指定位、判断出现奇数次的数、简单加密等。
// 注意事项：
//   - ^ 是位运算符，不要和求幂运算混淆（C++ 中 ^ 不是乘方）。

 #include <iostream>

using namespace std;

int main()
{
    // 异或的定义：相同为 0，不同为 1
    int a = 0b1010;
    int b = 0b0110;
    cout << (a ^ b) << endl;        // 1010 ^ 0110 = 1100，即 12

    // 标记位取反：与 0b1000 异或，可翻转第 4 位
    int c = 0b1000101;
    cout << (c ^ 0b1000) << endl;

    // 变量交换：利用异或性质，不用临时变量交换 d 和 e
    int d = 17;
    int e = 19;
    d = d ^ e;
    e = d ^ e;
    d = d ^ e;
    cout << d << " " << e << endl;  // 19 17

    // 3.1 任何数和0异或，还是它本身
    // 3.2 两个相同的数异或，结果为0
    // 3.3 异或满足交换律和结合律
    // 异或：不带进位的二进制加法

    // 4 出现奇数次的数（利用性质：成对的数异或后抵消，剩下出现奇数次的数）

    // 5 加密：把 x 与密钥 17 异或得到密文，再用 17 异或即可解密
    int x = 1314;
    cout << "520" << x << endl;        // 原始数据
    cout << "520" << (x^17) << endl;   // 异或加密后的数据



    return 0;
}
