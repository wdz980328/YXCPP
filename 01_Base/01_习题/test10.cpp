/*
 * 输入：输入数据有多行组成，首先是一个整数N，表示测试实例的个数，然后是N行数据，每行有6个整数，AH,AM,AS,BH,BM,BS,分别表示时间A和B所对应的时分秒，题目保证所有的数据合法
 * 输出：对于每个测试实例，输出A+B，每个输出结果也是由时分秒三部分组成，同时也要满足时间的规则，每个输出占一行。并且所有的部分都可以用32位整数表示
 */

// 输入一个t，代表t组数据，每组数据输入两个时间，时间分别为时分秒
//输出：输出t行，每行是一个时间，代表这组数据下的两个时间加和，注意考虑进位

// 【知识点说明】
// 本题考察时间（时分秒）的加法与“满 60 进位”的进制换算。
// 解题思路：
//   1. 先把两个时间的秒、分、时分别相加；
//   2. 秒满 60 则向分进位：分 += 秒/60，秒 %= 60；
//   3. 分满 60 则向时进位：时 += 分/60，分 %= 60。
// 其中 “/” 求商得到进位的数量，“%” 求余得到本位保留的数值。

#include <iostream>

using namespace std;

int main()
{
    int t;
    int ah,am,as;   // 时间 A 的时、分、秒
    int bh,bm,bs;   // 时间 B 的时、分、秒
    cin >> t;       // 读取数据组数 t
    while (t--) {
        cin >> ah >> am >> as;
        cin >> bh >> bm >> bs;
        as += bs;   // 秒相加
        am += bm;   // 分相加
        ah += bh;   // 时相加

        am += as / 60; // 秒满 60 向分进位
        as %= 60;      // 秒保留余数

        ah += am /60;  // 分满 60 向时进位
        am %= 60;      // 分保留余数

        cout << ah << ' ' << am << ' ' << as << endl; // 输出结果时分秒
    }

    return 0;
}
