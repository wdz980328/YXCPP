// 【知识点说明】
// 本题考察用字符打印图形：使用嵌套 for 循环输出由 '+'、'-'、'|'
// 组成的矩形边框。
// 解题思路：矩形宽为 n（内部 n 个 '-' 或空格）、高为 m（内部 m 行）。
//   1. 先打印上边框：一个 '+'，接着 n 个 '-'，再一个 '+'；
//   2. 打印中间 m 行：每行一个 '|'，n 个空格，再一个 '|'；
//   3. 最后打印下边框：同上边框。
// 外层循环控制行，内层循环控制列，是二维图形打印的典型做法。

#include <iostream>

using namespace std;

int main()
{
    int n,m;

    while (cin >> n >> m) {    // 反复读取矩形的宽 n 和高 m
        cout << '+';           // 上边框左侧 '+'
        for (int i=0; i<n; i++) {
            cout << '-';       // 上边框的 n 个 '-'
        }
        cout << '+';           // 上边框右侧 '+'

        for (int i=0; i<m; i++) {   // 打印中间 m 行
            cout << '|';            // 每行左侧 '|'
            for (int j = 0; j<n; j++) {
                cout << ' ';        // 中间 n 个空格
            }
            cout << '|' << endl;    // 每行右侧 '|' 并换行
        }

        cout << '+';           // 下边框左侧 '+'
        for (int i=0; i<n; i++) {
            cout << '-';       // 下边框的 n 个 '-'
        }
        cout << '+';           // 下边框右侧 '+'

    }

    return 0;
}
