// 成绩转换

/*
 * 输入一百分制的成绩，将其转换成对应的等级，具体转换规则如下：
 * 90-100为A
 * 80-89为B
 * 70-79为C
 * 60-69为D
 * 0-59为E
 *
 * 输入：输入数据有多组，每组占一行，由一个整数组成
 *
 * 输出：对于每组输入数据，输出一行，如果输入数据不在0-100范围内，请输出一行：“Score is error！”
 */

// 【知识点说明】
// 本题考察多分支选择结构 if / else if 的使用，用于把百分制成绩
// 按区间转换成等级（A/B/C/D/E）。
// 解题思路：用一系列 if / else if 依次判断分数所在的区间并给 ret 赋值；
// 若所有区间都不匹配（成绩超出 0~100），ret 保持初始值 '\0'，
// 据此判断输出错误提示还是等级字母。

#include <iostream>
using namespace std;

int main()
{
    int x;
    while (cin >> x) {          // 反复读取成绩，直到输入结束
        char ret = '\0';        // 初始化结果为空字符，用于标记是否匹配到区间
        if (x >= 90 && x <=100) {   // 90~100 为 A
            ret = 'A';
        }
        else if (x >= 80 && x <=89) { // 80~89 为 B
            ret = 'B';
        }
        else if (x >= 70 && x <=79) { // 70~79 为 C
            ret = 'C';
        }
        else if (x >= 60 && x <=69) { // 60~69 为 D
            ret = 'D';
        }
        else if (x >= 0 && x <=59) {  // 0~59 为 E
            ret = 'E';
        }
        if (ret == '\0') {           // 若未被赋值，说明成绩非法
            cout << "Score is error！" << endl;
        }
        else {
            cout << ret << endl;     // 输出等级
        }

    }

    return 0;
}
