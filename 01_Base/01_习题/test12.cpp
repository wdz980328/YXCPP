// 【知识点说明】
// 本题考察字符与 ASCII 码的关系以及大小写字母的判断。
// 解题思路：字符在内存中以整数（ASCII 码）存储，'A'~'Z' 和 'a'~'z'
// 都是连续编码，因此可用 x - 'A' + 1 得到字母的序号（A=1, B=2, ...）。
// 大写字母序号为正，小写字母序号取负；再与整数 y 相加得到最终结果。

#include <iostream>

using namespace std;

int main()
{
    int t;
    while(t--){
        char s[3];  // 字符数组，用于存放输入的字符
        char x;
        int y;
        int ans = 0;
        cin >> s;   // 读入字符串（实际只取第一个字符）

        x = s[0];   // 取出第一个字符作为 x
        cin >> y;   // 读入整数 y

        // 判断是否为大写字母
        if(x >= 'A' && x <= 'Z'){
            ans = y + (x - 'A' + 1); // 大写：序号为正，x-'A'+1 即 A=1,B=2...
        }
        // 判断是否为小写字母
        else if(x >= 'a' && x <= 'z'){
            ans = y - (x - 'a' + 1); // 小写：序号为负
        }
        cout << ans << endl;
        

    }
}
