//                                                按位取反

//
// 【知识点说明】
// 按位取反运算符 ~ 是一元运算符，对整数的每一个二进制位取反：
//   0 变 1，1 变 0。
// 运算规则：
//   在计算机中整数以补码存储，所以对任意整数 a，有 ~a = -(a + 1)。
//   例如 a = 1（二进制 ...0001），~a = ...1110，按补码解释为 -2。
// 注意事项：
//   - 取反结果与整数位数有关，不同编译器/平台下 int 位数可能不同。
//   - 取反后最高位通常变为 1，结果按有符号数解释为负数。

#include <iostream>

// ~

using namespace std;

int main()
{
    int a = 0b1;            // 二进制 1
    cout << (~a) << endl;   // ~1 = -2（补码运算：~a = -(a+1)）

    return 0;
}
