//                                      变量
//
// 【知识点说明】
// 变量（variable）是程序运行时用于存储数据的一块命名内存空间，
// 其值可以在程序运行过程中被改变。
//
// 概念要点：
// 1. 定义变量的一般格式：数据类型 变量名 = 初始值;
//    例如 int x = 1314; 表示定义 int 类型变量 x，并初始化为 1314。
// 2. 数据类型决定了变量占用内存的大小以及能存储的数据范围。
// 3. = 在这里表示"赋值/初始化"，即把右边的值存入左边的变量。
//
// 注意事项：
// 1. 变量必须先定义后使用，否则编译报错。
// 2. 变量名由字母、数字、下划线组成，且不能以数字开头，也不能与关键字同名。
// 3. 使用未初始化的局部变量会得到不确定的值（未定义行为），应养成定义时初始化。

#include <iostream>      // 头文件：提供输入输出流
using namespace std;     // 使用标准命名空间
int main()               // 程序入口
{
    //变量的定义：定义 int 类型变量 x 并初始化为 1314
    int x = 1314;
    //定义 int 类型变量 y 并初始化为 520
    int y = 520;

    cout << "x = " << x << endl;  // 输出变量 x 的值
    cout << "y = " << y << endl;  // 输出变量 y 的值


    return 0;            // 程序正常结束
}
