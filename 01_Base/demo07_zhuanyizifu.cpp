//                                      转义字符
//
// 【知识点说明】
// 转义字符（escape character）是以反斜杠 \ 开头的特殊字符，
// 用来表示那些无法直接输入或具有特殊含义的字符。
//
// 概念要点：
// 1. 常用转义字符：
//    \n 换行、\t 水平制表符(Tab)、\\ 反斜杠本身、
//    \0 空字符(字符串结束标志)、\a 响铃(报警)、\' 单引号、\" 双引号。
// 2. 转义字符在底层对应一个 ASCII 码值，例如 \n 对应 10、\a 对应 7，
//    可用 int(c) 查看其码值。
// 3. 反斜杠 + 数字可表示八进制/十六进制转义，如 \077、\x41（见文末注释）。
//
// 注意事项：
// 1. 想输出一个反斜杠本身，必须写成 \\，否则会被当作转义字符的开头。
// 2. \0 是空字符，作为 C 风格字符串的结束标志，输出时遇到 \0 会提前结束。
// 3. 转义字符整体仍是一个"字符"，占 1 字节。

#include <iostream>

using namespace std;

int main()
{
    char a = '\a';              // 响铃(报警)转义字符
    cout << int(a) <<endl;      // 输出 \a 的 ASCII 码值 7
    char n = '\n';              // 换行转义字符
    cout << "英雄算法联盟" << n;  // 输出字符串后换行

    cout << "英雄算法联盟\t夜深人静写算法" << endl;  // \t 产生一个 Tab 间隔
    cout << "英雄算法联盟\\夜深人静写算法" << endl;  // \\ 输出一个反斜杠
    cout << "英雄算法联盟\0夜深人静写算法" << endl;  // \0 是空字符，其后内容不会输出

    return 0;
}

