//                                                                  赋值运算符

//
// 【知识点说明】
// 赋值运算符用于把右侧的值赋给左侧的变量，最基本的是 =。
// 复合赋值运算符把“运算”和“赋值”合并成一步，例如：
//   +=  -=  *=  /=  %= 等。
// 运算规则：
//   1. x += y 等价于 x = x + y；
//      x -= y 等价于 x = x - y；其余同理。
//   2. 赋值表达式的值就是赋值后左侧变量的值。
// 注意事项：
//   - 左侧必须是可以被赋值的变量（左值），不能是常量或表达式。
//   - = 表示赋值，== 才表示判断相等，二者不要混淆。
//   - 复合赋值运算符是先取 x 的旧值参与运算，再把结果写回 x。

#include <iostream>

using namespace std;

int main()
{
    int x = 6;          // 初始化 x 为 6
    int y = 9;          // 初始化 y 为 9

    x = y;  //将y赋值给x：x 变为 9
    cout << x << endl;

    x += y; // x = x+y;  即 x = 9 + 9 = 18
    cout << x <<endl;

    x -= y; // x = x-y;  即 x = 18 - 9 = 9
    cout << x <<endl;

    x *= y; // x = x * y;  即 x = 9 * 9 = 81
    cout << x <<endl;

    x /= y; // x = x / y;  即 x = 81 / 9 = 9
    cout << x <<endl;



    return 0;
}
