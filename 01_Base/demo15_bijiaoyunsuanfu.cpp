//                                                      比较运算符

/*
 * =    <   >   <=   >=
 */


#include <iostream>

using namespace std;

int main()
{
    int a = 6;
    int b = 9;

    cout << (a == b) << endl;
    cout << (a != b) << endl;
    cout << (a > b) << endl;
    cout << (a < b) << endl;
    cout << (a >= b) << endl;
    cout << (a <= b) << endl;

    return 0;
}


