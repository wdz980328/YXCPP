//                                                      比较运算符

//
// 【知识点说明】
// 比较运算符（也叫关系运算符）用于比较两个值的大小关系，
// 比较的结果是布尔值：成立为 true(输出 1)，不成立为 false(输出 0)。
// 常见比较运算符：
//   == 等于、!= 不等于、> 大于、< 小于、>= 大于等于、<= 小于等于。
// 运算规则：
//   1. 先计算左右两边表达式的值，再进行比较。
//   2. 结果只有两种：true（输出为 1）或 false（输出为 0）。
// 注意事项：
//   - == 是判断相等，= 是赋值，两者很容易写错，务必区分。
//   - 不要用 == 直接比较两个浮点数是否完全相等（存在精度误差）。

/*
 * =    <   >   <=   >=
 */
// 注：上面第一项“=”应为“==”（等于），同时“!=”（不等于）也是比较运算符。

#include <iostream>

using namespace std;

int main()
{
    int a = 6;
    int b = 9;

    cout << (a == b) << endl;  // 相等比较：6 == 9 为假，输出 0
    cout << (a != b) << endl;  // 不等比较：6 != 9 为真，输出 1
    cout << (a > b) << endl;   // 大于：假，输出 0
    cout << (a < b) << endl;   // 小于：真，输出 1
    cout << (a >= b) << endl;  // 大于等于：假，输出 0
    cout << (a <= b) << endl;  // 小于等于：真，输出 1

    return 0;
}
