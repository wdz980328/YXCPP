//                                                  函数
//
// 【知识点说明】
// 函数是一段具有特定功能的、可重复调用的代码块，分为“函数定义”和“函数调用”。
// 定义函数时需要给出返回类型、函数名、参数列表和函数体；
// 调用函数时通过“函数名(实参)”的形式执行其内部代码。
//
// 语法规则：
//     返回类型 函数名(形参列表)
//     {
//         函数体;
//         return 返回值;   // 返回类型为 void 时可省略
//     }
//
// 注意事项：
// 1. 函数必须先声明（或定义）再调用，否则编译器找不到函数。
// 2. 返回类型必须与 return 返回值的类型一致（或能隐式转换）。
// 3. 一个函数的功能应尽量单一，便于复用和维护。

#include <iostream>

using namespace std;

// 函数定义：计算两个整数之和并返回结果
int add(int a, int b)
{
    int c = a+b;   // 用局部变量 c 保存求和结果

    return c;      // 返回计算结果
}


int main()
{
    int ret = add(1,7);      // 调用 add 函数，实参 1 和 7 传给形参 a 和 b
    cout << ret <<endl;      // 输出 add 返回的结果


    return 0;
}
