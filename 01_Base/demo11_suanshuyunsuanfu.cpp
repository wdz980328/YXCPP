// 【知识点说明】
// 算术运算符用于完成基本的数学运算，常见的有：
//   加法 +、减法 -、乘法 *、除法 /（取模 % 单独在 demo12 中介绍）。
// 运算规则：
//   1. 两个整数相除时，结果仍为整数，小数部分直接舍去（向 0 取整），
//      例如 6 / 9 的结果是 0。
//   2. 只要两个操作数中有一个是浮点数，结果就是浮点数，
//      例如 a * 1.0 / b 会得到带小数的结果。
//   3. 乘法运算可能超出 int 的取值范围导致溢出，
//      此时应先把操作数转换成 long long 等更大的整数类型再运算。
// 注意事项：
//   - 除法除数不能为 0，否则程序会运行出错。
//   - 整数除法不会四舍五入，需要小数结果时必须先进行类型转换。

#include <iostream>

using namespace std;

int main()
{
    int a = 6;                      // 定义整型变量 a
    int b = 9;                      // 定义整型变量 b
    cout << a + b << endl;          // 加法：6 + 9 = 15
    cout << a - b << endl;          // 减法：6 - 9 = -3
    cout << a * b << endl;          // 乘法：6 * 9 = 54
    cout << a / b << endl;          // 整数除法：结果为 0，小数部分被舍去
    cout << a * 1.0 / b << endl;    // 先转换为浮点数再除，得到 0.666667

    a = 10000000;
    b = 100000;
    cout << (long long)a * b << endl;   //超出整形范围，转换成 long long 类型

    return 0;
}
