//                                                                  逗号运算符

//
// 【知识点说明】
// 逗号运算符 , 是优先级最低的运算符，用于把多个表达式连接成一个表达式。
// 运算规则：
//   1. 从左到右依次计算每个子表达式。
//   2. 整个逗号表达式的值是最后一个子表达式的值。
//   3. 除了最后一个子表达式外，前面子表达式的值都会被丢弃，
//      它们通常只是用来产生“副作用”（如赋值、自增等）。
// 注意事项：
//   - 逗号还常被用作分隔符（如函数参数、变量声明），此时它只是分隔，
//     与“逗号运算符”含义不同。
//   - 由于优先级最低，用它给变量赋值时通常需要加括号。

#include <iostream>

using namespace std;

int main()
{
    int a = 1;
    a= (5-6, 8+9, 100/7); // -1, 17, 14；依次计算后，最终取最后一个值 14 赋给 a
    cout << a << endl;    // 14

    // 案例1：用临时变量交换 x 和 y 的值
    int x = 4;
    int y = 5;
    int tmp = x;   // 先把 x 存到临时变量
    x = y;         // 再把 y 赋给 x
    y = tmp;       // 最后把临时变量赋给 y
    cout << x << ' ' << y << endl;   // 5 4
    tmp = x, x=y, y=tmp;  // 用逗号运算符依次执行三条赋值语句，同样完成交换

    return 0;
}
