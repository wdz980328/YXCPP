/*
 *                          命名空间
 * 命名空间就像是一个容器或者一个独立的区域。用来组织和管理代码中的各种名称。
 * 想象一下，有很多程序员都在编写代码，
 * 很可能会出现不同人定义了相同名称的情况，如果没有命名空间，这些同名的名字
 * 就有可能会产生冲突，导致程序出现错误，而命名空间的存在可以有效地避免这种冲突
 */

