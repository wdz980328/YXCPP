//                          二维数组
//
// 【知识点说明】
// 二维数组可以理解成“数组的数组”，即每个元素本身又是一个一维数组，
// 常用来表示矩阵、表格等具有“行”和“列”概念的数据。
//
// 语法规则：
//     类型 数组名[行数][列数];
//     例如：int arr[3][4];   // 3 行 4 列，共 3*4 = 12 个元素
//
// 注意事项：
// 1. 两个下标都从 0 开始，元素访问方式为 arr[行下标][列下标]。
// 2. 定义时可用嵌套的 {} 逐行初始化，未给出的元素会自动补 0。
// 3. 二维数组在内存中按“行优先”连续存放，访问时同样不能越界。
#include <iostream>

using namespace std;

int main()
{
    int arr[3][4];          // 定义一个 3 行 4 列的二维数组
    // 双重循环遍历：外层控制行，内层控制列
    for (int i = 0; i<3; ++i) {
        for (int j = 0; j<4; ++j) {
            arr[i][j] = i * j;   // 给第 i 行第 j 列的元素赋值
        }
    }
    // 定义并初始化一个 4 行 4 列的二维数组，部分元素未给出，会自动补 0
    int b[4][4] = {
        {1,2},
        {2,3},
        {6,7,8},
        {9,1}
    };
    // 逐行逐列输出数组 b 的元素
    for (int i = 0; i<4; ++i) {
        for (int j = 0; j<4; ++j) {
            cout << b[i][j];     // 输出第 i 行第 j 列元素（不换行）
        }
        cout << endl;            // 每输出完一行换行
    }

    return 0;
}
