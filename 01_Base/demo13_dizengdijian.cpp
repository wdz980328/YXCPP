//                                                                  递增递减运算符

//
// 【知识点说明】
// 递增运算符 ++ 和递减运算符 -- 用于让变量加 1 或减 1，属于一元运算符。
// 它们都有“前缀”和“后缀”两种写法：
//   前缀 ++i / --i：先把变量加（减）1，再使用变量的值。
//   后缀 i++ / i--：先使用变量当前的值，再把变量加（减）1。
// 单独写成一句时（如 i++;）前缀后缀效果一样；
// 但一旦参与赋值或表达式，二者结果就会不同。
// 注意事项：
//   - 递增递减只能作用于变量（可修改的左值），不能作用于常量或表达式。
//   - 应避免在同一个表达式中多次修改同一个变量，否则结果难以确定。

#include <iostream>

using namespace std;

int main()
{
    int i = 6;
    i++;                    // 后缀递增，i 变为 7
    cout << i << endl;      // 7
    ++i;                    // 前缀递增，i 变为 8
    cout << i << endl;      // 8

    int j = 8;
    int x = i++;    // 先赋值，再递增：x 先取 i 当前值(8)，随后 i 变为 9
    int y = ++j;    // 先递增，再赋值：j 先变为 9，再把 9 赋给 y    效率高一点点

    cout << x << endl;      // 8
    cout << y << endl;      // 9

    return 0;
}
