//                                                      取模运算符

//
// 【知识点说明】
// 取模运算符 % 用于求两个整数相除后的余数，也常称为取余运算。
// 运算规则：
//   1. % 两边的操作数都必须是整数（浮点数不能直接使用 %）。
//   2. 结果的符号始终跟随被除数（左操作数），
//      例如 -100 % 9 = -1，100 % -9 = 1，-100 % -9 = -1。
//   3. 取模常用于判断奇偶、循环、把数限制在一定范围内等场景。
// 注意事项：
//   - 除数（右操作数）不能为 0，否则程序运行出错。
//   - 符号规则容易记错：结果符号只与被除数有关，与除数无关。

#include <iostream>

using namespace std;

int main()
{
    int a = 100;                // 被除数
    int b = 9;                  // 除数
    cout << a % b << endl;      // 100 % 9 = 1

    a = -100;                   // 被除数为负
    b = 9;
    cout << a % b << endl;      // -100 % 9 = -1（符号跟随被除数）

    a = 100;
    b = -9;                     // 除数为负
    cout << a % b << endl;      // 100 % -9 = 1（符号仍跟随被除数）

    a= -100;
    b = -9;
    cout << a % b << endl;      // -100 % -9 = -1

    return 0;
}
