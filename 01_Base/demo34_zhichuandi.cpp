//          函数值传递
//
// 【知识点说明】
// 值传递是函数参数传递的一种方式：调用函数时，实参的值被复制一份传给形参，
// 函数体内对形参的任何修改都不会影响实参本身。
//
// 语法规则：
//     返回类型 函数名(类型 形参名, ...) { ... }   // 形参只是实参的副本
//
// 注意事项：
// 1. 值传递中形参与实参是两份独立的内存，修改形参不影响实参。
// 2. 若要真正交换实参的值，需要使用指针或引用传递，值传递做不到。
// 3. 值传递会复制数据，对于较大的对象会有额外的拷贝开销。

#include <iostream>

using namespace std;

// 尝试交换两个整数：但因为是值传递，只会交换形参的副本，不影响实参
void swap(int a, int b)
{
    cout << "a = " << a << endl;   // 输出传入副本 a 的值
    cout << "b = " << b << endl;   // 输出传入副本 b 的值
    cout << "================" << endl;
    int tmp = a;                   // 用临时变量保存 a，进行交换
    a = b;
    b = tmp;
    cout << "a = " << a << endl;   // 输出交换后的形参 a
    cout << "b = " << b << endl;   // 输出交换后的形参 b
}

int main()
{
    int a = 6;
    int b = 9;
    swap(a,b);   // 值传递：把 a、b 的值复制给形参，函数结束后 a、b 不变

    return 0;
}
