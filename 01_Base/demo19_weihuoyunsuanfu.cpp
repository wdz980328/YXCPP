//                                                  位或运算符

//
// 【知识点说明】
// 位或运算符 | 是“按位或”，对两个整数二进制表示的每一位进行或运算。
// 运算规则（对单个二进制位）：
//   0 | 0 = 0，其余（0 | 1、1 | 0、1 | 1）都为 1，即“有 1 必 1”。
// 常见用途：
//   - 把某些位“置 1”：与对应位为 1 的掩码相或。
//   - 合并多个标记位。
// 注意事项：
//   - | 是位运算符，|| 是逻辑或，二者不同。

#include <iostream>

using namespace std;

int main()
{
    // 位或 | 有1即1
    int a = 0b1010;
    int b = 0b0110;
    cout << (a | b) << endl;        // 1010 | 0110 = 1110，即 14

    // 设置标记位：把第 4 位（0b1000）置 1
    int c = 0b100111;
    cout << (c | 0b1000) << endl;

    // 置空标记位（此处借助 c|d 后再减去 d 演示清除最低位）
    int d = 0b000001;
    cout << ((c | d) -d) << endl;

    // 低位连续0变成1：e - (e - 1) 可得到最低位 1 及其后的掩码
    int e = 0b1010010000;
    cout << (e - (e - 1)) << endl;

    return 0;
}
