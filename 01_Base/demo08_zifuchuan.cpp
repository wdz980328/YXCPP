//                                 C 风格字符串 / 字符数组
//
// 【知识点说明】
// C 风格字符串本质上是"以空字符 \0 结尾的字符数组"，用双引号 "" 表示。
// 本文件同时演示了 C++ 标准库提供的 string 类型（需包含 <string>）。
//
// 概念要点：
// 1. C 风格字符串定义：char 数组名[] = "字符串常量";
//    编译器会自动在末尾补一个 \0 作为结束标志。
// 2. sizeof(数组) 得到的是整个数组占用的字节数，含末尾的 \0。
// 3. string 是 C++ 标准库中的字符串类型，比字符数组更安全、更方便，
//    支持用 + 进行字符串拼接。
//
// 注意事项：
// 1. C 风格字符串必须以 \0 结尾，否则无法正确判断字符串结束位置。
// 2. 用 sizeof 求 C 风格字符串长度时，结果比实际字符个数多 1（末尾 \0）。
// 3. 输出字符数组名 a 时，会从首地址开始逐个输出字符，直到遇到 \0。
// 4. string 与 C 风格字符串不同：string 是类类型，支持动态长度和丰富操作。

#include <iostream>     // 提供输入输出流
#include <string>       // 提供 string 类型

using namespace std;

/*
 * char 变量名[] = "字符串常量"
 */

int main()
{
    char a[] = "英雄算法联盟";          // C 风格字符串（字符数组），末尾自动补 \0
    cout << sizeof(a) << endl;        // 输出数组 a 占用的总字节数（含末尾 \0）
    cout << a << endl;                // 输出整个 C 风格字符串

    string b = "夜深人静写算法";        // C++ 标准库 string 类型
    cout << b + ";" << endl;          // string 支持 + 拼接，输出 "夜深人静写算法;"

    return 0;
}
